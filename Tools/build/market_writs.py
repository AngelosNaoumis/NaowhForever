"""Build which Craftsman's Writs each profession can fill, for The Market's Prices filter.

A Forever writ is an item ("Craftsman's Writ: Distilled Firewater") that starts a quest of the same
name. In Tools/data/quest_entity_catalog.json that quest's item objectives (objectives["3"]) are
the writ itself, then the item the customer asks for. The profession is whichever one crafts that
item in Professions' recipe data (NaowhForever_Professions/Data/RecipeData.lua, keyed by skill
line): a recipe row reads `spell = ..., item = <made item>`. An item two professions craft lists
the writ under both, since either can fill it.

A writ whose quest does not have exactly those two objectives, whose asked-for item no profession
crafts, or a writ item seen twice stops the build, so a change in the data is caught here, not in
game.

Writes NaowhForever_Market/Data/Writs.lua: skill line -> the writ item IDs it fills, in ID order.
The addon reads IDs only, and the client names the professions and items, so it works in every
client language. Run it again when the quest catalog or the recipe data changes.

Usage: python Tools/build/market_writs.py
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402
from journal import header, write  # noqa: E402

CATALOG = paths.DATA / "quest_entity_catalog.json"
RECIPES = paths.ROOT / "NaowhForever_Professions" / "Data" / "RecipeData.lua"
OUT = paths.ROOT / "NaowhForever_Market" / "Data" / "Writs.lua"

WRIT = "Craftsman's Writ: "      # a writ quest's name starts so
ITEM_OBJECTIVES = "3"            # objectives[3]: the items a quest asks for
PROFESSION = re.compile(r"^    \[(\d+)\] = \{")
MADE = re.compile(r"\bspell = \d+, item = (\d+)")
PER_LINE = 10


def made_by(text):
    """Item ID -> the skill lines whose recipes make it, from RecipeData.lua's text."""
    makers, profession = {}, None
    for line in text.splitlines():
        match = PROFESSION.match(line)
        if match:
            profession = int(match.group(1))
            continue
        for item in MADE.findall(line):
            makers.setdefault(int(item), set()).add(profession)
    return makers


def writs(quests):
    """Writ item ID -> the item ID its quest asks for, for every Craftsman's Writ quest."""
    found = {}
    for quest_id, quest in quests.items():
        if not str(quest.get("name", "")).startswith(WRIT):
            continue
        items = ((quest.get("source_fields") or {}).get("objectives") or {}).get(ITEM_OBJECTIVES) or {}
        if len(items) != 2:
            sys.exit(f"quest {quest_id}: {len(items)} item objectives, not the writ and one asked-for item")
        writ, wanted = int(items["1"]["1"]), int(items["2"]["1"])
        if writ in found:
            sys.exit(f"quest {quest_id}: writ {writ} is already another quest's")
        if writ == wanted:
            sys.exit(f"quest {quest_id}: writ {writ} asks for itself")
        found[writ] = wanted
    return found


def by_profession(wanted, makers):
    """Skill line -> its writ item IDs in order, for each writ's asked-for item."""
    fills = {}
    for writ in sorted(wanted):
        professions = makers.get(wanted[writ])
        if not professions:
            sys.exit(f"writ {writ}: no profession makes item {wanted[writ]}")
        for profession in professions:
            fills.setdefault(profession, []).append(writ)
    return fills


def lua(fills):
    lines = header("Writs.lua", "the Craftsman's Writs each profession can fill, generated by "
                   "Tools/build/market_writs.py")
    lines.append("ns.Market.WRITS = {")
    for profession in sorted(fills):
        ids = fills[profession]
        lines.append(f"    [{profession}] = {{")
        for i in range(0, len(ids), PER_LINE):
            lines.append("        " + ", ".join(str(x) for x in ids[i:i + PER_LINE]) + ",")
        lines.append("    },")
    lines.append("}")
    return lines


def main():
    quests = json.loads(CATALOG.read_text(encoding="utf-8"))
    wanted = writs(quests)
    fills = by_profession(wanted, made_by(RECIPES.read_text(encoding="utf-8")))
    write(OUT, lua(fills))
    counts = ", ".join(f"{profession}: {len(ids)}" for profession, ids in sorted(fills.items()))
    print(f"{len(wanted)} writs -> {OUT.relative_to(paths.ROOT)} ({counts})")


if __name__ == "__main__":
    main()
