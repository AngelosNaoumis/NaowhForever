"""Tests for Tools/build/market_writs.py: which writs each profession fills, from the quest catalog and
the recipe data, and the checks that stop the build. Offline; the data is made up here, plus one
check of the real files. From the repo root:

    python -m unittest discover -s Tools/tests
"""
import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402,F401
import market_writs as mw  # noqa: E402

ALCHEMY, LEATHERWORKING, TAILORING = 171, 165, 197

RECIPES = """ns.RecipeData = {
    [171] = {
        ranks = {
            { cap = 225, skill = 125, item = 16084, vendors = {} },
        },
        recipes = {
            { spell = 1, item = 900, skill = 250 },
        },
    },
    [165] = {
        recipes = {
            { spell = 2, item = 901, skill = 275 },
        },
    },
    [197] = {
        recipes = {
            { spell = 3, item = 901, skill = 275 }, { spell = 4, item = 902, skill = 1 },
        },
    },
}
"""


def quest(name, *items):
    return {"name": name, "source_fields": {"objectives": {
        "3": {str(i + 1): {"1": item} for i, item in enumerate(items)}}}}


class MarketWritsTest(unittest.TestCase):
    def test_made_by_reads_recipe_rows_only(self):
        makers = mw.made_by(RECIPES)
        self.assertEqual(makers[900], {ALCHEMY})
        self.assertEqual(makers[901], {LEATHERWORKING, TAILORING})
        self.assertNotIn(16084, makers, "a rank's book is not something the profession makes")

    def test_writs_reads_the_writ_and_the_asked_for_item(self):
        quests = {"1": quest("Craftsman's Writ: Potion", 500, 900), "2": quest("Some Other Quest", 7, 8)}
        self.assertEqual(mw.writs(quests), {500: 900})

    def test_writs_stops_on_odd_objectives(self):
        for bad in ({"1": quest("Craftsman's Writ: A", 500)},
                    {"1": quest("Craftsman's Writ: A", 500, 900), "2": quest("Craftsman's Writ: B", 500, 901)},
                    {"1": quest("Craftsman's Writ: A", 500, 500)}):
            with self.assertRaises(SystemExit):
                mw.writs(bad)

    def test_by_profession_lists_shared_items_under_both(self):
        fills = mw.by_profession({502: 901, 500: 900, 501: 901}, mw.made_by(RECIPES))
        self.assertEqual(fills, {ALCHEMY: [500], LEATHERWORKING: [501, 502], TAILORING: [501, 502]})

    def test_by_profession_stops_on_an_item_nobody_makes(self):
        with self.assertRaises(SystemExit):
            mw.by_profession({500: 999}, mw.made_by(RECIPES))

    def test_lua_is_the_market_table(self):
        lines = mw.lua({ALCHEMY: list(range(1, 13))})
        self.assertEqual(lines[0], "-- Writs.lua: the Craftsman's Writs each profession can fill, generated by "
                         "Tools/build/market_writs.py.")
        self.assertIn("ns.Market.WRITS = {", lines)
        self.assertIn("    [171] = {", lines)
        self.assertIn("        11, 12,", lines)

    def test_the_real_data_maps_every_writ(self):
        wanted = mw.writs(json.loads(mw.CATALOG.read_text(encoding="utf-8")))
        fills = mw.by_profession(wanted, mw.made_by(mw.RECIPES.read_text(encoding="utf-8")))
        self.assertEqual(len(wanted), 150)
        self.assertEqual({writ for ids in fills.values() for writ in ids}, set(wanted))


if __name__ == "__main__":
    unittest.main()
