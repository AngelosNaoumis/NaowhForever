"""Build the item each Craftsman's Writ asks for, from quest_entity_catalog.json (Tools/data).

A writ is an item that starts its quest ("Craftsman's Writ: Distilled Firewater" starts the quest
of that name), and the quest's item objectives are the writ itself, which must be in your bags to
hand in, and the item the customer asked for. So the requested item is the one item objective that
is not the writ. A writ quest that no item starts, that two items start, or whose objectives leave
other than one item stops the build, as does one writ starting two quests, so a change in the
catalog is caught here, not in game.

The catalog's objectives carry no counts, so the table has none: the tooltip prices one.

Writes NaowhForever_QoL/Loot/WritRequestsData.lua: writ item ID -> requested item ID, which
Auction Prices prices on the writ's tooltip. It reads IDs only, so it works in every client language.
Run it again after quest_entity_catalog.json changes.

Usage: python Tools/build/writ_requests.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402
from journal import header, write  # noqa: E402

ROOT = paths.ROOT
CATALOG = paths.DATA / "quest_entity_catalog.json"
OUT = ROOT / "NaowhForever_QoL" / "Loot" / "WritRequestsData.lua"

WRIT = "Craftsman's Writ: "      # a writ quest's name starts so
ITEMS = "3"                      # the item list in startedBy and objectives


def item_list(field):
    """The item IDs of a catalog startedBy or objectives field, in its order."""
    entries = (field or {}).get(ITEMS) or {}
    found = []
    for key in sorted(entries, key=int):
        entry = entries[key]
        found.append(int(entry["1"] if isinstance(entry, dict) else entry))
    return found


def requests(catalog):
    """Writ item ID -> the item ID its quest asks for, for every Craftsman's Writ quest."""
    found = {}
    for quest_id, quest in catalog.items():
        name = quest.get("name") or ""
        if not name.startswith(WRIT):
            continue
        fields = quest.get("source_fields") or {}
        writs = item_list(fields.get("startedBy"))
        if len(writs) != 1:
            sys.exit(f"quest {quest_id} {name!r}: started by {len(writs)} items {writs}, not one")
        writ = writs[0]
        wanted = [item for item in item_list(fields.get("objectives")) if item != writ]
        if len(wanted) != 1:
            sys.exit(f"quest {quest_id} {name!r}: asks for {len(wanted)} items {wanted} besides the writ, not one")
        if writ in found:
            sys.exit(f"writ {writ} starts more than one quest")
        found[writ] = wanted[0]
    return found


def lua(found):
    lines = header(OUT.name, "the item each Craftsman's Writ asks for, by item ID, generated by "
                             "Tools/build/writ_requests.py from quest_entity_catalog.json")
    lines.append("ns.WritRequests = {")
    for writ in sorted(found):
        lines.append(f"    [{writ}] = {found[writ]},")
    lines.append("}")
    return lines


def main():
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    found = requests(catalog)
    if not found:
        sys.exit(f"{CATALOG.name} lists no Craftsman's Writ quests")
    write(OUT, lua(found))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(found)} writs")


if __name__ == "__main__":
    main()
